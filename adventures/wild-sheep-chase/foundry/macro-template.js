/**
 * Setup Wild Sheep Chase — Thai copy of the Plutonium-imported one-shot "The Wild Sheep Chase" (WSC, Winghorn Press).
 * For Foundry VTT v14 + D&D 5e system 6.x
 *
 * How to use:
 *   1. Import "The Wild Sheep Chase" with Plutonium (journal + creatures/items, so the @UUID links resolve).
 *   2. Macro Directory → Create Macro → Type: "Script" → paste this file → Execute (GM only).
 *   3. Then run Pin-Wild-Sheep-Chase to put the map pins on the Noke's Tower scenes.
 *
 * What it does:
 *   Creates the journal "The Wild Sheep Chase (TH)" in the same folder as the English Plutonium journal, which is left
 *   untouched — one page per section (Summary, Baaaa-d News, The House in the Woods, ...). Body text is Thai; headings
 *   stay English. Same layout, links, rolls and stat-block embeds as the English one.
 *   Re-running updates the pages in place (journal name, folder and pages you add yourself are left alone); the old
 *   single-page version from earlier runs is replaced.
 *   Generated by adventures/wild-sheep-chase/foundry/build.py — edit segments-th.json there and rebuild, not in Foundry.
 */
(async () => {
  const NAME = "The Wild Sheep Chase (TH)";
  const PAGES = /*PAGES*/null;

  if (!game.user.isGM) return ui.notifications.error("GM only.");

  const english = game.journal.find(j => j.flags?.plutonium?.source === "WSC" && !j.flags?.world?.wscThai);
  let entry = game.journal.find(j => j.flags?.world?.wscThai);
  if (!entry) {
    entry = await JournalEntry.create({
      name: NAME,
      folder: english?.folder?.id ?? null,
      ownership: english?.ownership ?? { default: CONST.DOCUMENT_OWNERSHIP_LEVELS.NONE },
      flags: { world: { wscThai: true } }
    });
  }

  const sortStep = CONST.SORT_INTEGER_DENSITY;
  const create = [];
  const update = [];
  PAGES.forEach((p, i) => {
    const data = {
      name: p.name,
      sort: (i + 1) * sortStep,
      "text.content": p.content,
      "text.format": CONST.JOURNAL_ENTRY_PAGE_FORMATS.HTML
    };
    const page = entry.pages.find(x => x.flags?.world?.wscPage === p.key);
    if (page) update.push({ _id: page.id, ...data });
    else create.push({
      name: p.name, type: "text", sort: data.sort,
      text: { content: p.content, format: CONST.JOURNAL_ENTRY_PAGE_FORMATS.HTML },
      title: { show: true, level: 1 },
      flags: { world: { wscPage: p.key } }
    });
  });
  // the one-page version written by earlier runs of this macro
  const legacy = entry.pages.filter(x => !x.flags?.world?.wscPage
    && x.text?.content?.includes('data-roll-name-ancestor="The Wild Sheep Chase"')).map(x => x.id);

  if (update.length) await entry.updateEmbeddedDocuments("JournalEntryPage", update);
  if (create.length) await entry.createEmbeddedDocuments("JournalEntryPage", create);
  if (legacy.length) await entry.deleteEmbeddedDocuments("JournalEntryPage", legacy);
  ui.notifications.info(`"${entry.name}": ${PAGES.length} pages ready`
    + (legacy.length ? " (old single page removed — re-run Pin-Wild-Sheep-Chase)." : "."));
  entry.sheet.render(true);
})();
